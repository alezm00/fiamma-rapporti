const { chromium } = require('playwright');
const fs = require('fs');
const [SP, FX, BASE = 'http://localhost:8801/'] = process.argv.slice(2);
const log = (...a) => console.log('•', ...a);
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, isMobile: true, hasTouch: true, locale: 'it-IT', timezoneId: 'Europe/Rome', acceptDownloads: true });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  page.on('dialog', (d) => d.accept());
  await page.goto(BASE);
  await page.waitForSelector('#view-home:not([hidden])');
  await page.evaluate(() => navigator.serviceWorker.ready);
  // aspetta che il service worker abbia messo in cache tutti i file
  await page.waitForFunction(async () => (await caches.keys()).length > 0 && (await (await caches.open((await caches.keys())[0])).keys()).length >= 30, null, { timeout: 20000 });
  log('cache ->', await page.evaluate(async () => { const k = (await caches.keys())[0]; return k + ' (' + (await (await caches.open(k)).keys()).length + ' file)'; }));
  await ctx.setOffline(true);
  await page.reload();
  await page.waitForSelector('#view-home:not([hidden])', { timeout: 15000 });
  log('senza rete: home aperta');
  await page.click('#btn-new');
  await page.waitForSelector('#view-editor:not([hidden])');
  await page.fill('#c-name', 'Cliente Offline');
  await page.click('#e-measure-add');
  await page.setInputFiles('#in-file', `${FX}/sample-10389.json.gz`);
  await page.waitForSelector('#view-measure:not([hidden])');
  log('misura letta (lettore QR / gzip in locale)');
  await page.click('#m-back');
  await page.waitForSelector('#view-editor:not([hidden])');
  await page.setInputFiles('#in-gallery', [`${SP}/img/small00.jpg`]);
  await page.waitForFunction(() => document.querySelectorAll('#photo-grid > div').length === 1, null, { timeout: 30000 });
  await page.click('#btn-close');
  await page.waitForFunction(() => /Rapporto n\./.test(document.getElementById('e-title').textContent));
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-pdf-save')]);
  const p = `${SP}/dl/offline-new.pdf`;
  await dl.saveAs(p);
  log('PDF senza rete ->', dl.suggestedFilename(), fs.statSync(p).size, 'byte');
  // lettore QR da foto (wasm in cache)
  await page.click('#e-back');
  await page.waitForSelector('#view-home:not([hidden])');
  await page.click('#btn-quick-scan');
  await page.waitForSelector('#view-scan:not([hidden])');
  await page.setInputFiles('#in-photo', `${FX}/qr-sample.png`);
  await page.waitForSelector('#view-measure:not([hidden])', { timeout: 20000 });
  log('QR da foto senza rete -> ok:', await page.textContent('#r-title'));
  assert(errors.length === 0, 'errori: ' + errors.join(' // '));
  await browser.close();
  log('ok');
})().catch((e) => { console.error('FAILED', e.message); process.exit(1); });
